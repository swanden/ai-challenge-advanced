#!/bin/bash
# Показ для видео по Дню 10: двухуровневый инференс.
#
#   bash week-2/task-10/scripts/demo.sh
#
# Флаги: -t по таймеру, -s N множитель пауз, -n без прогонов.

set -u
SPEED=1; MANUAL=1; RUN=1; ROOT="week-2/task-10"

while getopts "s:tmn" opt; do
    case "$opt" in
        s) SPEED="$OPTARG" ;; t) MANUAL=0 ;; m) MANUAL=1 ;; n) RUN=0 ;;
        *) echo "неизвестный флаг" >&2; exit 2 ;;
    esac
done
[ -d "$ROOT" ] || { echo "Запускать из корня репозитория" >&2; exit 1; }

B=$(printf '\033[1m'); DIM=$(printf '\033[2m'); OFF=$(printf '\033[0m')
CYAN=$(printf '\033[36m'); YELLOW=$(printf '\033[33m')

pause() {
    if [ "$MANUAL" = "1" ]; then
        printf '\n%s— дальше по Enter —%s' "$DIM" "$OFF"; read -r _; return
    fi
    secs=$(awk "BEGIN{printf \"%d\", ($1 * $SPEED) + 0.5}")
    [ "$secs" -lt 1 ] && return
    while [ "$secs" -gt 0 ]; do
        printf '\r%s   %s%s ' "$DIM" "$secs" "$OFF"; sleep 1; secs=$((secs - 1))
    done
    printf '\r          \r'
}
section() { clear; printf '%s%s%s\n' "$CYAN$B" "$1" "$OFF"; printf '%s\n\n' "$DIM$(printf '%.0s─' $(seq 1 72))$OFF"; }
say() { printf '%s\n' "$1"; }
cmd() { printf '\n%s$ %s%s\n\n' "$YELLOW" "$1" "$OFF"; }

section "День 10. Micro-model first: проверка перед LLM"
say "Языковая модель — дорогой инструмент: сотни миллисекунд"
say "на ответ. Задание предлагает поставить перед ней что-то"
say "дешёвое, что справится с простым само."
say ""
say "Задание разрешает три варианта первого уровня:"
say "маленькую LLM, эмбеддинги или обычный ML-классификатор."
say "${B}Реализованы все три, основной — третий.${OFF}"
pause 9

section "Чем это отличается от Дня 8"
say "Механика похожа: дешёвый уровень отвечает, при сомнении"
say "запрос уходит наверх. Но граница проходит в другом месте."
say ""
say "В Дне 8 обе ступени — языковые модели, разница только"
say "в размере. Здесь первый уровень вообще не модель:"
say "он сравнивает вход с тем, что уже видел."
say ""
say "Микросекунды вместо сотен миллисекунд. И вопрос другой:"
say "${B}не «нужна ли модель побольше», а «нужна ли модель вообще».${OFF}"
pause 11

section "И ещё одно отличие, после Дня 7"
say "Там уверенность значила «насколько модель убеждена»,"
say "и мы измерили: с правильностью она не связана,"
say "ошибки шли с вероятностью 1.00."
say ""
say "Здесь уверенность значит «насколько этот вход похож"
say "на то, что я знаю»."
say ""
say "${B}Это внешняя мера, а не самооценка. Может сработать там,${OFF}"
say "${B}где самооценка провалилась — это и проверяем.${OFF}"
pause 11

section "Данные, которые наконец пошли в дело"
say "Обучающая выборка — train.jsonl из Дня 6."
say "64 примера, которые за четыре дня ни разу не участвовали"
say "ни в одном замере."
say ""
say "Собирались они под файнтюн, которого не случилось."
say "Теперь на них учится классификатор, а проверка на eval"
say "остаётся честной: первый уровень видел только train."
pause 10

section "Что записано в ожиданиях до прогона"
if [ -f "$ROOT/docs/micro.md" ]; then
    grep -E '^\*\*' "$ROOT/docs/micro.md" | sed 's/\*\*//g' | cut -c1-70
fi
pause 10

section "Прогон"
cmd "go run ./$ROOT/cmd/tiered -kind ngram"
if [ "$RUN" = "1" ]; then
    go run "./$ROOT/cmd/tiered" -kind ngram -note "прогон для видео"
else
    say "${DIM}(пропущено флагом -n)${OFF}"
fi
pause 18

section "Ряд из шести точек"
say "День 6, монолит                    56%"
say "День 8, малая модель               63%"
say "День 8, маршрутизация              68%"
say "День 8, большая модель             74%"
say "День 9, декомпозиция               53%"
say "День 10, два уровня                 ?"
say ""
say "${B}Но главная цифра здесь не точность, а то, сколько${OFF}"
say "${B}запросов удалось снять с языковой модели.${OFF}"
pause 10
