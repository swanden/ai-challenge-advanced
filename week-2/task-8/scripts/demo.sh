#!/bin/bash
# Показ для видео по Дню 8: маршрутизация между моделями.
#
# По умолчанию шаг делается по Enter.
#
# Запускать из корня репозитория:
#
#   bash week-2/task-8/scripts/demo.sh
#
# Флаги:
#   -t       по таймеру вместо Enter, с обратным отсчётом
#   -s N     множитель пауз для таймера
#   -n       не выполнять прогоны, только показ и разбор

set -u

SPEED=1
MANUAL=1
RUN=1
ROOT="week-2/task-8"

while getopts "s:tmn" opt; do
    case "$opt" in
        s) SPEED="$OPTARG" ;;
        t) MANUAL=0 ;;
        m) MANUAL=1 ;;
        n) RUN=0 ;;
        *) echo "неизвестный флаг" >&2; exit 2 ;;
    esac
done

if [ ! -d "$ROOT" ]; then
    echo "Запускать из корня репозитория ai-challenge-advanced" >&2
    exit 1
fi

B=$(printf '\033[1m'); DIM=$(printf '\033[2m'); OFF=$(printf '\033[0m')
CYAN=$(printf '\033[36m'); YELLOW=$(printf '\033[33m')

pause() {
    if [ "$MANUAL" = "1" ]; then
        printf '\n%s— дальше по Enter —%s' "$DIM" "$OFF"
        read -r _
        return
    fi
    secs=$(awk "BEGIN{printf \"%d\", ($1 * $SPEED) + 0.5}")
    [ "$secs" -lt 1 ] && return
    while [ "$secs" -gt 0 ]; do
        printf '\r%s   %s%s ' "$DIM" "$secs" "$OFF"
        sleep 1
        secs=$((secs - 1))
    done
    printf '\r          \r'
}

section() {
    clear
    printf '%s%s%s\n' "$CYAN$B" "$1" "$OFF"
    printf '%s\n\n' "$DIM$(printf '%.0s─' $(seq 1 72))$OFF"
}

say() { printf '%s\n' "$1"; }
cmd() { printf '\n%s$ %s%s\n\n' "$YELLOW" "$1" "$OFF"; }

# ── 1. Задача ───────────────────────────────────────────────────────────────
section "День 8. Routing между моделями"
say "Маршрутизируется классификатор из Дней 6 и 7:"
say "по формулировке задачи определяется, куда она едет в сборке."
say ""
say "Первая ступень — qwen2.5:7b, точность известна: 9 из 16."
say "Вторая ступень — qwen2.5:14b, вдвое больше параметров."
say ""
say "Одно семейство выбрано намеренно: тогда разница в ответах"
say "говорит о размере, а не о том, что модель просто другая."
pause 9

# ── 2. Почему не только confidence ──────────────────────────────────────────
section "Почему одной уверенности недостаточно"
say "День 7 измерил слепое пятно: обе ошибки на contract-change"
say "прошли с вероятностью 1.00 и 0.93 при полном согласии выборок."
say ""
say "Малая модель не сомневается — она просто не знает, что смена"
say "публичного контракта в этом проекте требует человека."
say ""
say "${B}Значит эскалация по неуверенности не сработает ровно там,${OFF}"
say "${B}где ошибка опаснее всего.${OFF}"
pause 10

section "Четыре признака эскалации"
say "Три смотрят на ответ малой модели, и все три достаются"
say "из одного вызова — logprobs приходят тем же ответом:"
say "  формат, вероятность, отрыв от альтернативы, длина ответа"
say ""
say "Четвёртый смотрит на сам запрос и модели не требует вовсе:"
say "существительное про контракт рядом с глаголом изменения."
say ""
say "Второй урок Дня 7: там сомнение стоило 4 вызова на вход."
say "Для роутера это абсурд — экономия съедалась бы расходом."
pause 11

section "Три режима вместо одного"
say "small — всё на малой. Это пол."
say "route — маршрутизация по признакам."
say "big   — всё на большой. Это потолок и полная цена."
say ""
say "Цифра роутера сама по себе не значит ничего."
say "Значение ей придают пол и потолок."
pause 8

# ── 3. Прогоны ──────────────────────────────────────────────────────────────
section "Прогон: все три режима"
cmd "go run ./$ROOT/cmd/route -mode all"
if [ "$RUN" = "1" ]; then
    go run "./$ROOT/cmd/route" -mode all -note "прогон для видео"
else
    say "${DIM}(пропущено флагом -n)${OFF}"
fi
pause 18

section "Контрольный прогон: без разбора формулировки"
say "Гипотеза: весь выигрыш держится на признаке,"
say "который вообще не обращается к модели. Проверяю."
cmd "go run ./$ROOT/cmd/route -mode all -markers=false"
if [ "$RUN" = "1" ]; then
    go run "./$ROOT/cmd/route" -mode all -markers=false -note "контроль для видео"
else
    say "${DIM}(пропущено флагом -n)${OFF}"
fi
pause 18

# ── 4. Разбор ───────────────────────────────────────────────────────────────
section "Маршрутизация окупилась"
say "small 63%  →  route 68%  →  big 74%"
say ""
say "Разрыв между полом и потолком — 11 пунктов."
say "Роутер забрал 5 из них, обратившись к большой модели"
say "5 раз вместо 30."
say ""
say "${B}Почти половина доступного качества за шестую часть цены.${OFF}"
pause 9

section "Но выигрыш дал не confidence"
say "Выключаем разбор формулировки — и route схлопывается"
say "до 63%, то есть до уровня малой модели."
say ""
say "Признак уверенности сработал ровно один раз за оба прогона,"
say "на eval-08. И там большая модель ответила так же неверно."
say ""
say "${B}Работает двадцать строк разбора текста запроса,${OFF}"
say "${B}стоящие ноль вызовов модели.${OFF}"
pause 10

section "Разбор формулировки сработал наполовину"
say "Четыре срабатывания: одно попадание (eval-04, исправлено"
say "на contract-change), два впустую, одно на пограничном."
say ""
say "А на eval-03 не сработал вовсе — там тоже contract-change."
say "«отдавать 201 и заголовок Location вместо нынешнего 200»:"
say "глагол есть, а слова «заголовок» в моём словаре нет."
say ""
say "${B}Дописать одну строку — соблазн. Но это подгонка${OFF}"
say "${B}под известные примеры, и словарь остался как был.${OFF}"
pause 11

section "Большая модель не универсально лучше"
say "Исправила eval-04, eval-10, eval-13."
say "И сломала eval-07, который малая брала верно:"
say "feature превратился в refactor."
say ""
say "Три исправления против одной поломки."
say ""
say "${B}Эскалация — не бесплатная страховка, а размен.${OFF}"
say "${B}Чем больше входов уходит наверх, тем выше и риск порчи.${OFF}"
pause 10

section "Что оказалось неверным в моих ожиданиях"
say "Записаны до прогона, в docs/routing.md."
say ""
say "«Большая не исправит contract-change» — неверно наполовину:"
say "eval-04 исправила, eval-03 нет."
say ""
say "«Разбор будет срабатывать зря» — верно, но не предугадано,"
say "что он ещё и пропускает нужное."
say ""
say "«Длина ответа не сработает» — верно, ноль срабатываний."
say "«route будет ближе к big» — нет, ровно посередине."
pause 11

section "Про задержки — отрицательный результат"
say "Первый прогон без прогрева дал бессмыслицу: большая модель"
say "быстрее малой. Причина — загрузка весов легла на тот режим,"
say "что шёл первым."
say ""
say "После прогрева цифры осмысленнее, но разброс между запусками"
say "одного режима — до полутора раз."
say ""
say "${B}Честная метрика стоимости здесь — число обращений${OFF}"
say "${B}к большой модели: 5 против 30. Оно измерено точно.${OFF}"
pause 10

section "Результат"
say "Рабочий routing с fallback-логикой: четыре признака,"
say "три режима для сравнения, отчёты в evidence/."
say ""
say "Главный вывод: сначала дешёвые детерминированные признаки,"
say "потом модельные. Разбор запроса дал весь эффект за ноль"
say "вызовов, механизм уверенности из Дня 7 — ничего за четыре."
say ""
say "И ход в День 9: словарь из одиннадцати слов надо заменить"
say "коротким вопросом к модели — «меняет ли задача контракт,"
say "да или нет». Это и есть декомпозиция инференса."
pause 10
