#!/bin/bash
# Показ для видео по Дню 9: декомпозиция инференса.
#
# Запускать из корня репозитория:
#
#   bash week-2/task-9/scripts/demo.sh
#
# Флаги:
#   -t   по таймеру вместо Enter
#   -s N множитель пауз для таймера
#   -n   без прогонов, только показ и разбор

set -u

SPEED=1
MANUAL=1
RUN=1
ROOT="week-2/task-9"

while getopts "s:tmn" opt; do
    case "$opt" in
        s) SPEED="$OPTARG" ;;
        t) MANUAL=0 ;;
        m) MANUAL=1 ;;
        n) RUN=0 ;;
        *) echo "неизвестный флаг" >&2; exit 2 ;;
    esac
done

if [ ! -d "$ROOT" ]; then
    echo "Запускать из корня репозитория ai-challenge-advanced" >&2
    exit 1
fi

B=$(printf '\033[1m'); DIM=$(printf '\033[2m'); OFF=$(printf '\033[0m')
CYAN=$(printf '\033[36m'); YELLOW=$(printf '\033[33m')

pause() {
    if [ "$MANUAL" = "1" ]; then
        printf '\n%s— дальше по Enter —%s' "$DIM" "$OFF"
        read -r _
        return
    fi
    secs=$(awk "BEGIN{printf \"%d\", ($1 * $SPEED) + 0.5}")
    [ "$secs" -lt 1 ] && return
    while [ "$secs" -gt 0 ]; do
        printf '\r%s   %s%s ' "$DIM" "$secs" "$OFF"
        sleep 1
        secs=$((secs - 1))
    done
    printf '\r          \r'
}

section() {
    clear
    printf '%s%s%s\n' "$CYAN$B" "$1" "$OFF"
    printf '%s\n\n' "$DIM$(printf '%.0s─' $(seq 1 72))$OFF"
}

say() { printf '%s\n' "$1"; }
cmd() { printf '\n%s$ %s%s\n\n' "$YELLOW" "$1" "$OFF"; }

section "День 9. Декомпозиция инференса"
say "Задачу выбирать не пришлось — она измерена трижды."
say ""
say "День 6: точность 56%, обе ошибки на contract-change."
say "День 7: механизм уверенности этих ошибок не увидел —"
say "        они прошли с вероятностью 1.00 и 0.93."
say "День 8: маршрутизация дала +5 пунктов, но словарь"
say "        поймал один contract-change из двух."
say ""
say "${B}Один класс провалили три разных механизма.${OFF}"
say "${B}Декомпозиция — четвёртая попытка, лечение адресное.${OFF}"
pause 11

section "В чём идея разбивки"
say "Монолит предлагает выбрать один класс из восьми."
say "contract-change конкурирует с семью соседями,"
say "и модель берёт ближайший знакомый: feature или refactor."
say ""
say "Многоэтапная схема убирает конкуренцию: сначала"
say "отдельный бинарный вопрос про контракт, и только"
say "при ответе «нет» — выбор из семи оставшихся."
pause 10

section "Почему это должно сработать"
say "Первое: вероятность делится между двумя ответами,"
say "а не размазывается по восьми."
say ""
say "Второе, важнее: бинарный вопрос можно задать содержательно."
say "Перечислить, что считается контрактом — коды статусов,"
say "заголовки, форма тела ответа, путь маршрута, сигнатура."
say ""
say "${B}В общем промпте так не сделать, не подсказав заодно${OFF}"
say "${B}определения остальных семи классов.${OFF}"
pause 11

section "Три этапа"
say "1. Нормализация — четыре признака строгого вида:"
say "   visible, artifact, mode, product. Одна строка, не проза."
say ""
say "2. Решение — вопрос про контракт, затем класс из семи."
say ""
say "3. Сборка — модель НЕ вызывается. Проверяется, что признаки"
say "   не противоречат классу: review без артефакта, docs"
say "   с продуктом-кодом, refactor с изменением поведения."
say ""
say "Правила третьего этапа — из таксономии Дня 6. Спрашивать"
say "их у модели значит добавлять шум там, где ответ известен."
pause 12

section "Прогон: монолит, три этапа, два этапа"
cmd "go run ./$ROOT/cmd/pipeline -mode all"
if [ "$RUN" = "1" ]; then
    go run "./$ROOT/cmd/pipeline" -mode all -note "прогон для видео"
else
    say "${DIM}(пропущено флагом -n)${OFF}"
fi
pause 18

section "Прогон: нормализация на модели поменьше"
say "Задание разрешает разные модели по этапам. Проверяю,"
say "переживёт ли конвейер удешевление первого этапа."
cmd "go run ./$ROOT/cmd/pipeline -mode multistage -normalize-model qwen2.5:3b"
if [ "$RUN" = "1" ]; then
    go run "./$ROOT/cmd/pipeline" -mode multistage -normalize-model qwen2.5:3b \
        -note "нормализация на 3b, для видео"
else
    say "${DIM}(пропущено флагом -n)${OFF}"
fi
pause 16

section "Что записано в ожиданиях до прогона"
if [ -f "$ROOT/docs/stages.md" ]; then
    grep -E '^\*\*' "$ROOT/docs/stages.md" | sed 's/\*\*//g' | cut -c1-70
fi
say ""
say "Сверяю с тем, что вышло, — по цифрам с экрана."
pause 10

section "Что вышло"
say "монолит      63%   32 вызова"
say "три этапа    53%   94 вызова"
say "два этапа    53%   60 вызовов"
say ""
say "${B}Декомпозиция проиграла монолиту.${OFF}"
say ""
say "Но contract-change: 0/2 у монолита → 2/2 у двух этапов."
say "Адресный вопрос решил класс, который провалили"
say "три предыдущих механизма."
pause 10

section "Почему проиграла"
say "Первый этап оказался чистым расходом: без него та же"
say "точность вдвое дешевле. На 3b он ломался в трети случаев —"
say "точность не изменилась."
say ""
say "Второй этап сужением списка испортил четыре класса:"
say "bug-fix 5/5 → 2/5, feature 1/2 → 0/2, testing 2/2 → 1/2."
say ""
say "${B}Два приобретённых ответа против четырёх потерянных.${OFF}"
pause 11

section "Промпт учит искать то, что перечисляет"
say "Первая версия вопроса перечисляла признаки контракта —"
say "коды статусов, заголовки, форму ответа."
say "Модель стала отвечать «да» везде, где эти слова есть:"
say "8 ложных срабатываний из 32."
say ""
say "Переписал через различие: «станет ДРУГИМ» против"
say "«приводится К описанному». Помогло вдвое."
say ""
say "${B}Но eval-01 остался ложным «да» — притом что вписан${OFF}"
say "${B}в промпт дословным примером.${OFF}"
pause 11

section "У других декомпозиция выиграла"
say "dpmn, извлечение 9 полей: 56% → 63%."
say "Ткачёв, решение по претензии: 14/16 → 16/16."
say ""
say "Разница объяснима. У них разбивка снимает нагрузку"
say "со СТРУКТУРЫ ответа: девять полей, шесть правил."
say "У нас ответ — одно слово из восьми, структуры нет."
say ""
say "${B}Его вывод точнее нашего: декомпозировать стоит${OFF}"
say "${B}извлечение, а не классификацию.${OFF}"
pause 11

section "Главное"
say "Отрицательный результат получен вовремя, и получен он"
say "только потому, что рядом стоял монолит."
say ""
say "Без варианта A отчёт содержал бы цифру 53% и вывод"
say "«работает» — сравнивать было бы не с чем."
say ""
say "${B}Вариант A в задании — не формальность, а то, что${OFF}"
say "${B}превращает демонстрацию в измерение.${OFF}"
pause 10
