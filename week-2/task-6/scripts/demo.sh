#!/bin/bash
# Показ для видео по Дню 6: проходит по артефактам задания и запускает то,
# что запускается, сопровождая всё подписями на экране — расчёт на запись
# без голоса.
#
# По умолчанию шаг делается по Enter: так темпом управляешь ты, и экран
# никогда не выглядит зависшим. Таймер включается отдельным флагом.
#
# Запускать из корня репозитория:
#
#   bash week-2/task-6/scripts/demo.sh
#
# Флаги:
#   -t       по таймеру вместо Enter; во время ожидания видно обратный отсчёт
#   -s N     множитель пауз для таймера, по умолчанию 1 (например -s 1.5 медленнее)
#   -n       не выполнять прогоны (без Ollama и сети), только показ файлов

set -u

SPEED=1
MANUAL=1
RUN=1
ROOT="week-2/task-6"

while getopts "s:tmn" opt; do
    case "$opt" in
        s) SPEED="$OPTARG" ;;
        t) MANUAL=0 ;;
        m) MANUAL=1 ;;
        n) RUN=0 ;;
        *) echo "неизвестный флаг" >&2; exit 2 ;;
    esac
done

if [ ! -d "$ROOT" ]; then
    echo "Запускать из корня репозитория ai-challenge-advanced" >&2
    exit 1
fi

# ANSI-оформление: заголовки должны быть различимы на записи.
B=$(printf '\033[1m'); DIM=$(printf '\033[2m'); OFF=$(printf '\033[0m')
CYAN=$(printf '\033[36m'); YELLOW=$(printf '\033[33m')

# pause ждёт перед следующим экраном. В ручном режиме — Enter, в режиме
# таймера — обратный отсчёт, который затем стирается: без него пауза
# неотличима от зависшего скрипта.
pause() {
    if [ "$MANUAL" = "1" ]; then
        printf '\n%s— дальше по Enter —%s' "$DIM" "$OFF"
        read -r _
        return
    fi
    secs=$(awk "BEGIN{printf \"%d\", ($1 * $SPEED) + 0.5}")
    [ "$secs" -lt 1 ] && return
    while [ "$secs" -gt 0 ]; do
        printf '\r%s   %s%s ' "$DIM" "$secs" "$OFF"
        sleep 1
        secs=$((secs - 1))
    done
    printf '\r          \r'
}

section() {
    clear
    printf '%s%s%s\n' "$CYAN$B" "$1" "$OFF"
    printf '%s\n\n' "$DIM$(printf '%.0s─' $(seq 1 72))$OFF"
}

say() { printf '%s\n' "$1"; }

cmd() {
    printf '\n%s$ %s%s\n\n' "$YELLOW" "$1" "$OFF"
}

# ── 1. О чём речь ───────────────────────────────────────────────────────────
section "День 6. DataSet — маршрутный классификатор задач"
say "Задача под тюнинг: классификация."
say "На вход — формулировка задачи. На выход — один класс,"
say "определяющий, куда задача едет дальше в сборке notes-api."
say ""
say "Классы взяты не с потолка: это профили селектора Дня 2"
say "плюс типы задач из пула Дня 5, плюс один добавленный."
pause 7

# ── 2. Таксономия ───────────────────────────────────────────────────────────
section "Восемь классов"
say "bug-fix          неверное поведение, найти причину и починить"
say "feature          новая функциональность, аддитивная"
say "refactor         перестройка без изменения внешнего поведения"
say "testing          продукт работы — проверки: тесты, smoke, ворота"
say "docs             привести документацию в соответствие коду"
say "research         вопрос об устройстве кода, репозиторий не меняется"
say "review           оценить готовый код или диф"
say "contract-change  выполнение меняет публичный контракт"
pause 9

section "Ключевой класс: contract-change"
say "Задача, выполнение которой меняет публичный контракт:"
say "сигнатуру экспортированного метода, форму JSON-ответа,"
say "код статуса на успешном пути, путь маршрута."
say ""
say "Такие задачи нельзя брать в автономный цикл без человека."
say "Правило приоритета: contract-change перекрывает любой другой класс."
say ""
say "${B}Этого знания у общей модели нет — на нём и строится замер.${OFF}"
pause 8

section "Почему определений классов нет в системном промпте"
grep -m1 'const SystemPrompt' "$ROOT/internal/dataset/dataset.go" | fold -s -w 72
say ""
say "Промпт перечисляет имена и не объясняет ни одного."
say "Положи определения в промпт — базовая модель ответит не хуже"
say "дообученной, и мерить будет нечего."
pause 8

# ── 3. Датасет ──────────────────────────────────────────────────────────────
section "Датасет: одна запись master.jsonl"
head -1 "$ROOT/dataset/master.jsonl" | fold -s -w 72
say ""
say "У каждой записи есть происхождение: реальная она или синтетическая"
say "и из какого файла недели 1 взята формулировка."
pause 8

section "Формат обучения: messages из трёх ролей"
head -1 "$ROOT/dataset/train.jsonl" | fold -s -w 72
pause 8

section "Состав датасета"
printf 'master.jsonl : %s примеров\n' "$(wc -l < "$ROOT/dataset/master.jsonl" | tr -d ' ')"
printf 'train.jsonl  : %s\n' "$(wc -l < "$ROOT/dataset/train.jsonl" | tr -d ' ')"
printf 'eval.jsonl   : %s\n' "$(wc -l < "$ROOT/dataset/eval.jsonl" | tr -d ' ')"
printf 'реальных     : %s (требуется минимум 20%%)\n' \
    "$(grep -c '"real": true' "$ROOT/dataset/master.jsonl" | tr -d ' ')"
say ""
say "Разбиение детерминированное, без генератора случайных чисел:"
say "внутри класса примеры сортируются по идентификатору,"
say "в eval уходят третий и восьмой. Прогон на другой машине"
say "даёт побайтово те же файлы."
pause 9

# ── 4. Валидация ────────────────────────────────────────────────────────────
section "Скрипт валидации"
say "Проверяет требования задания — валидный JSON, три роли, непустой content —"
say "и то, без чего датасет портится тихо: дубли, перекрытие train и eval,"
say "отсутствие класса, перекос, границы длины, полноту провенанса."
cmd "go run ./$ROOT/cmd/validate"
if [ "$RUN" = "1" ]; then
    go run "./$ROOT/cmd/validate"
else
    say "${DIM}(пропущено флагом -n)${OFF}"
fi
pause 9

# ── 5. Baseline ─────────────────────────────────────────────────────────────
section "Baseline: замер ДО обучения"
say "Те же шестнадцать отложенных примеров, тот же системный промпт,"
say "temperature 0. Это точка отсчёта, с которой будет сравниваться"
say "дообученная модель на Днях 9–10."
say ""
say "Модель локальная: gpt-4o-mini из условия отпал — OpenAI закрыл"
say "self-serve файнтюн, и неделя переведена на локальные модели."
pause 8

section "Прогон baseline на qwen2.5:7b через Ollama"
cmd "go run ./$ROOT/cmd/baseline -base-url http://localhost:11434/v1 -key-env \"\" -model qwen2.5:7b -n 0"
if [ "$RUN" = "1" ]; then
    go run "./$ROOT/cmd/baseline" \
        -base-url http://localhost:11434/v1 -key-env "" -model qwen2.5:7b -n 0 \
        -note "прогон для видео"
else
    say "${DIM}(пропущено флагом -n)${OFF}"
fi
pause 14

# ── 6. Что показал замер ────────────────────────────────────────────────────
section "Что показал замер"
say "Локально, qwen2.5:7b, шестнадцать примеров: точность 56%,"
say "формат соблюдён в 100% ответов, 2.6 токена на ответ."
say ""
say "В облаке, тот же Qwen2.5-7B в полной точности через роутер"
say "Hugging Face: 78% на девяти примерах — прогон оборвался"
say "на HTTP 402, включённые кредиты исчерпаны."
say ""
say "${B}contract-change: ноль из двух на ОБЕИХ площадках.${OFF}"
say ""
say "Полноточная модель на чужом железе ошиблась ровно так же,"
say "как квантованная на моём. Значит дело не в квантовании"
say "и не в размере модели, а в отсутствии знания о проекте."
say "Это и есть случай, когда файнтюн оправдан."
pause 12

section "Сохранённые отчёты прогонов"
ls -1 "$ROOT/evidence"/*.json 2>/dev/null || say "${DIM}отчётов пока нет${OFF}"
say ""
latest=$(ls -t "$ROOT/evidence"/baseline-qwen2.5*.json 2>/dev/null | head -1)
if [ -n "${latest:-}" ]; then
    grep -E '"(accuracy|format_compliance|avg_latency_ms|avg_completion_tokens)"' "$latest"
fi
pause 8

# ── 7. Критерии ─────────────────────────────────────────────────────────────
section "Критерии «стало лучше», зафиксированные до прогона"
say "Точность: не ниже 71%, то есть плюс пятнадцать пунктов к нынешним 56%."
say "Полнота по contract-change: два из двух вместо нынешнего ноля."
say "Формат: сто процентов ответов одним словом."
say ""
say "Оговорка честности: критерий по длине ответа — не больше пяти токенов —"
say "выполнен уже сейчас, 2.6. Обещанной экономии токенов не будет:"
say "базовая модель и так отвечает одним словом. Критерий остаётся"
say "страховкой от ухудшения, а не доказательством пользы."
pause 11

# ── 8. Клиент файнтюна ──────────────────────────────────────────────────────
section "Усиление: клиент запуска файнтюна"
grep -n "// Шаг" "$ROOT/cmd/finetune/main.go" | sed 's/:[[:space:]]*\/\// /' | cut -c1-72
say ""
say "Загрузка файла, создание задания, опрос статуса до терминального."
say "Каждый шаг пишется в журнал вместе с кодом ответа и телом,"
say "в том числе неуспешный."
say ""
say "Не запускается: условие требует только подготовить код."
say "И запустить всё равно бы не вышло — OpenAI закрыл self-serve"
say "файнтюн для организаций, которые раньше не обучали."
pause 11

# ── 9. Итог ─────────────────────────────────────────────────────────────────
section "Результат"
say "Датасет JSONL: 80 примеров, train 64 / eval 16, реальных 25%."
say "Скрипт валидации."
say "Baseline: 16 ответов локально, 9 в облаке, отчёты в evidence/."
say "Критерии оценки, зафиксированные до прогона."
say "Клиент для запуска файнтюна."
say ""
say "${B}Дальше по неделе: LoRA на этой же локальной модели${OFF}"
say "${B}и сравнение с этой точкой отсчёта.${OFF}"
pause 8