#!/usr/bin/env bash
# Показ Дня 15 для видео. Пауза по Enter между шагами; таймер -t убирает паузы.
# Весь текст на экране, без озвучки.
set -euo pipefail

TIMER=0
for a in "$@"; do case "$a" in -t) TIMER=1;; esac; done
pause() { if [ "$TIMER" = 1 ]; then sleep 3; else read -r -p $'\n[Enter] '; fi; }

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$ROOT"

clear
cat <<'TXT'
День 15. Red Team — ломаем гейтвей соседа (@kgdnm, day13/guard-proxy).

Мишень запущена не по сети: его guard'ы — чистые функции над текстом,
правила портированы в internal/target из его же исходников и сверены построчно.
Раннер бьёт по настоящему детектору партнёра. Рядом с каждым пробоем — контроль.
TXT
pause

echo "1. Ожидания записаны ДО прогона — четыре пробоя, каждый привязан к строке его кода:"
echo
grep -E '^[0-9]\.' week-3/task-15/docs/expectations.md
pause

echo "2. Прогон всех проб во всех режимах входа:"
pause
go run ./week-3/task-15/cmd/redteam

cat <<'TXT'

Контроль 20/20 — детектор партнёра ловит то, что обязан: ключ, email, телефон,
одинарный base64. Значит порт достоверен, и pass на пробое — дыра в правиле.

Четыре пробоя подтвердились:
  A2  несоседний split рвёт склейку границей слова
  A3  двойной base64 — декодирование одноуровневое
  A4  ghp_ 32 символа против его порога 36
  O2  утечка промпта по-русски мимо английских маркеров
TXT
pause

echo "3. Первый прогон вскрыл ошибку в НАШЕМ порте, не в его коде — и раннер это поднял сам:"
echo "   RE2 не умеет lookaround, телефонное правило (?<!\\w)…(?!\\w) потеряло границы"
echo "   и ловило хвост ключа как номер. Починено постфильтром, контроль стал 20/20."
echo
echo "Полный разбор — week-3/task-15/README.md"
